"""Test the `ghmem index` extraction, rendering, and build."""

import json
from pathlib import Path

import pytest

from ghmem.aliases import IssueOrPRNumber
from ghmem.exceptions import MalformedFrontmatterError
from ghmem.index_cmd import (
    IndexEntry,
    IndexSummary,
    build_index,
    cited_numbers,
    render_index,
)
from ghmem.ledger import FetchEvent, Ledger, RoutingEvent
from ghmem.store import Store

HEAT_FIXTURE = Path(__file__).parent / "fixtures" / "heat_corpus.jsonl"

# A discussion node appended to the heat fixture so the store carries a
# discussion (number 7, distinct from the issues 1..5) — the one thing
# `heat_corpus` lacks and citation resolution must sort after scored items.
_DISCUSSION_NODE: FetchEvent = {
    "type": "discussion",
    "data": {
        "id": "D_7",
        "number": 7,
        "title": "a sidebar",
        "body": "b",
        "author": {"login": "octavia"},
        "createdAt": "2026-06-01T09:00:00Z",
        "updatedAt": "2026-06-02T10:00:00Z",
        "category": {"name": "Q&A"},
        "answer": None,
        "authorAssociation": "MEMBER",
    },
}


@pytest.fixture
def index_store(tmp_path: Path) -> Store:
    """Return a Store of the heat fixture's issues plus one discussion (#7)."""
    fetch_path = tmp_path / "fetch.jsonl"
    lines = HEAT_FIXTURE.read_text().splitlines()
    lines.append(json.dumps(_DISCUSSION_NODE))
    fetch_path.write_text("\n".join(lines) + "\n")
    store = Store.open(tmp_path / "cache.sqlite")
    routing: Ledger[RoutingEvent] = Ledger(tmp_path / "routing.jsonl")
    store.rebuild_from_ledgers(Ledger(fetch_path), routing)
    return store


def _route(store: Store, tmp_path: Path, item_id: str, topic: str) -> None:
    """Route the corpus item `item_id` to `topic` in the mirror."""
    routing: Ledger[RoutingEvent] = Ledger(tmp_path / "routing.jsonl")
    event: RoutingEvent = {
        "type": "route",
        "data": {
            "session": "s",
            "item_id": item_id,
            "verdict": topic,
            "note": "n",
            "item_updated_at": "2026-01-01T00:00:00Z",
        },
    }
    store.record_routing_event(routing, event)


def test_cited_numbers_plain_citation() -> None:
    """A bare `#N` in ordinary prose is extracted.

    When: the body names an issue in a plain sentence
    Then: its number is returned
    """
    assert cited_numbers("This rests on #2374 for the ruler.") == [2374]


def test_cited_numbers_appearance_order() -> None:
    """Numbers come back in the order they appear, not sorted.

    When: the body cites #3107 before #93
    Then: the list preserves that order
    """
    assert cited_numbers("first #3107 then #93") == [3107, 93]


def test_cited_numbers_deduplicates_keeping_first() -> None:
    """A number cited twice appears once, at its first position.

    When: #93 is cited before and after #1138
    Then: #93 appears once, ahead of #1138
    """
    assert cited_numbers("#93 and #1138 and again #93") == [93, 1138]


def test_cited_numbers_ignores_fenced_code() -> None:
    """A `#N` inside a fenced block is not a citation.

    When: the only `#N` sits inside a ``` fence
    Then: nothing is extracted
    """
    body = "prose\n```\n# heading #99\ncolor: #282828\n```\nmore"
    assert cited_numbers(body) == []


def test_cited_numbers_ignores_inline_code() -> None:
    """A `#N` inside an inline span is not a citation.

    When: the number sits inside backticks
    Then: nothing is extracted
    """
    assert cited_numbers("set `colorcolumn #80` here") == []


def test_cited_numbers_drops_block_quotes() -> None:
    """A `#N` on a block-quote line is excluded; prose `#N` is kept.

    When: a quoted line mentions #93 and the synthesizer's own line cites #2374
    Then: only #2374 is returned
    """
    body = "> a maintainer wrote about #93\n\nWe route this to #2374."
    assert cited_numbers(body) == [2374]


def test_cited_numbers_ignores_url_embedded_number() -> None:
    """A number inside a github URL is not a bare citation.

    When: the body contains a full pull URL ending in a number
    Then: the lookbehind guard rejects it
    """
    assert cited_numbers("see https://github.com/x/y/pull/123 today") == []


def test_cited_numbers_stops_at_word_boundary() -> None:
    """`#12a` is not read as `#12`.

    When: digits are followed immediately by a letter
    Then: the reference does not match
    """
    assert cited_numbers("version #12a shipped") == []


_HEADER = (
    "# Design topic index\n\n"
    "<!-- Generated by `ghmem index` from the topic docs. Do not edit. -->\n"
)


def test_render_empty_index_is_header_only() -> None:
    """An index with no topics renders the header and nothing else.

    When: the summary has no entries
    Then: the output is exactly the header block
    """
    assert render_index(IndexSummary(entries=[])) == _HEADER


def test_render_synthesized_line_links_and_carries_description() -> None:
    """A synthesized topic links to its file and shows its hook and numbers.

    When: a synthesized entry has a description and two numbers
    Then: the line is a markdown link with the description and the numbers
    """
    summary = IndexSummary(
        entries=[
            IndexEntry(
                name="options-parsimony",
                synthesized=True,
                description="a new option needs an argument against every alternative",
                numbers=[2374, 3107],
            )
        ]
    )

    assert render_index(summary) == (
        _HEADER + "\n- [options-parsimony](options-parsimony.md) — a new option needs "
        "an argument against every alternative (#2374, #3107)\n"
    )


def test_render_pending_line_has_no_link() -> None:
    """A pending topic has no link and is marked not yet synthesized.

    When: an entry is pending with one number
    Then: the line is unlinked, flagged, and carries the number
    """
    summary = IndexSummary(
        entries=[
            IndexEntry(
                name="softwrap", synthesized=False, description=None, numbers=[93]
            )
        ]
    )

    assert render_index(summary) == (
        _HEADER + "\n- softwrap — *not yet synthesized* (#93)\n"
    )


def test_render_caps_numbers_at_five_with_ellipsis() -> None:
    """A line showing more than five numbers keeps five and appends `…`.

    When: an entry rests on six numbers
    Then: only the first five show, followed by an ellipsis
    """
    summary = IndexSummary(
        entries=[
            IndexEntry(
                name="clipboard",
                synthesized=True,
                description="OSC 52",
                numbers=[93, 1138, 2374, 1746, 3107, 249],
            )
        ]
    )

    assert render_index(summary) == (
        _HEADER + "\n- [clipboard](clipboard.md) — OSC 52 "
        "(#93, #1138, #2374, #1746, #3107, …)\n"
    )


def test_render_entry_with_no_numbers_has_no_suffix() -> None:
    """A topic resting on no resolvable citation shows no number suffix.

    When: a synthesized entry has an empty number list
    Then: the line ends at the description, no parentheses
    """
    summary = IndexSummary(
        entries=[
            IndexEntry(
                name="norms", synthesized=True, description="all NFR", numbers=[]
            )
        ]
    )

    assert render_index(summary) == (_HEADER + "\n- [norms](norms.md) — all NFR\n")


def _write_doc(design_dir: Path, name: str, description: str, body: str) -> None:
    """Write a topic doc with a `description:` frontmatter and a body."""
    design_dir.mkdir(exist_ok=True)
    (design_dir / f"{name}.md").write_text(
        f"---\ndescription: {description}\n---\n{body}", encoding="utf-8"
    )


def test_build_index_resolves_orders_and_filters(
    index_store: Store, tmp_path: Path
) -> None:
    """A synthesized line is heat-ordered, discussion-last, filtered.

    When: a doc cites #5 and #1 (issues), #282828 (a hex colour), a
      block-quoted #3, and discussion #7
    Then: the line keeps only the resolvable citations, ranks the issues
      by heat (#1 before #5), sorts the discussion after them, and drops
      the hex colour and the quoted number
    """
    design = tmp_path / "design"
    _write_doc(
        design,
        "ruler",
        "line up wrapped text with the ruler",
        "We fold #5 and #1 here.\n"
        "A colour #282828 is not a citation.\n"
        "> a maintainer mentioned #3\n"
        "Also discussion #7.\n",
    )

    summary = build_index(index_store, design)

    assert summary.entries == [
        IndexEntry(
            name="ruler",
            synthesized=True,
            description="line up wrapped text with the ruler",
            numbers=[1, 5, 7],
        )
    ]


def test_build_index_indexes_pending_topic(index_store: Store, tmp_path: Path) -> None:
    """A routed topic with no doc is a pending entry, numbered from its items.

    When: item #2 is routed to topic "softwrap" and no softwrap.md exists
    Then: the index carries a pending softwrap entry citing #2
    """
    design = tmp_path / "design"
    design.mkdir()
    item2 = index_store.get_issue_or_pr(IssueOrPRNumber(2))
    _route(index_store, tmp_path, item2.id, "softwrap")

    summary = build_index(index_store, design)

    assert summary.entries == [
        IndexEntry(name="softwrap", synthesized=False, description=None, numbers=[2])
    ]


def test_build_index_interleaves_pending_and_synthesized_alphabetically(
    index_store: Store, tmp_path: Path
) -> None:
    """Pending and synthesized topics share one alphabetical list.

    When: pending topic "alpha" (routed #1) and synthesized doc "zebra"
      (no resolvable citations) both exist
    Then: they interleave by name — alpha (pending) before zebra
      (synthesized) — and the citation-free doc carries no numbers
    """
    design = tmp_path / "design"
    _write_doc(design, "zebra", "a late topic", "no citations in this body\n")
    item1 = index_store.get_issue_or_pr(IssueOrPRNumber(1))
    _route(index_store, tmp_path, item1.id, "alpha")

    summary = build_index(index_store, design)

    assert [(e.name, e.synthesized, e.numbers) for e in summary.entries] == [
        ("alpha", False, [1]),
        ("zebra", True, []),
    ]


def test_build_index_skips_the_index_file(index_store: Store, tmp_path: Path) -> None:
    """INDEX.md is not read as a topic doc.

    When: a frontmatter-less INDEX.md sits in the design dir
    Then: build_index ignores it rather than failing to parse it
    """
    design = tmp_path / "design"
    design.mkdir()
    (design / "INDEX.md").write_text("# Design topic index\n", encoding="utf-8")

    assert build_index(index_store, design).entries == []


def test_build_index_raises_on_missing_description(
    index_store: Store, tmp_path: Path
) -> None:
    """A doc whose frontmatter lacks description is a surfaced error.

    When: a doc's frontmatter carries no description field
    Then: build_index raises rather than indexing a blank hook
    """
    design = tmp_path / "design"
    design.mkdir()
    (design / "broken.md").write_text(
        "---\ntitle: no hook here\n---\nbody\n", encoding="utf-8"
    )

    with pytest.raises(MalformedFrontmatterError):
        build_index(index_store, design)
