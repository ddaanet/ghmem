"""Regenerate `docs/design/INDEX.md` — the recall surface — from topic docs.

Three concerns, three functions. `cited_numbers` is the pure text
extractor: a doc body in, the issue/PR/discussion numbers its prose
cites out, in appearance order. It applies the *syntactic* rules only
(strip code, drop block quotes, match bare `#N`); corpus resolution —
keeping only numbers a real item carries — is the caller's job, since
that is the caller who holds the `Store`. Keeping the two apart lets
each be tested on its own.
"""

import re
from dataclasses import dataclass
from pathlib import Path

import msgspec.yaml

from ghmem.exceptions import MalformedFrontmatterError
from ghmem.heat import HEAT_WEIGHTS
from ghmem.store import Store

_MAX_NUMBERS = 5
"""How many citation numbers an index line shows before it elides.

A hot topic can rest on thirty numbers, and a thirty-number line is unreadable.
The full set stays in the topic doc's own body; the index line is a hook, not a
bibliography. Arbitrary but real — heat ordering decides which five survive, so
the cap needs no second judgement.
"""

_HEADER = (
    "# Design topic index\n\n"
    "<!-- Generated by `ghmem index` from the topic docs. Do not edit. -->\n"
)
"""The INDEX.md preamble.

The generated-file comment is load-bearing: the
parent spec forbids agent edits, so the file must say so where an agent
will read it.
"""


@dataclass(frozen=True, slots=True)
class IndexEntry:
    """One topic's index line, resolved but not yet rendered.

    `numbers` is the full resolved-and-heat-ordered citation set;
    `render_index` applies the five-number cap. `description` is the
    doc's hook line and is present exactly when the topic is
    synthesized — a pending topic has a file-less line and no hook.
    """

    name: str
    synthesized: bool
    description: str | None
    numbers: list[int]


@dataclass(frozen=True, slots=True)
class IndexSummary:
    """The whole regenerated index: its entries plus the recap counts."""

    entries: list[IndexEntry]

    @property
    def topic_count(self) -> int:
        """Return how many topics the index covers."""
        return len(self.entries)

    @property
    def synthesized_count(self) -> int:
        """Return how many topics have a synthesized doc."""
        return sum(entry.synthesized for entry in self.entries)

    @property
    def pending_count(self) -> int:
        """Return how many topics are routed but not yet synthesized."""
        return self.topic_count - self.synthesized_count


# Fenced blocks (```…```) and inline spans (`…`): a `#N` inside code is
# never a citation. DOTALL so a fence spans lines; the inline arm
# forbids a newline so an unclosed backtick cannot swallow a paragraph.
_CODE = re.compile(r"```.*?```|`[^`\n]*`", re.DOTALL)

# A block-quote line — optional leading space, then `>`. Quoted prose is
# the maintainers' words, not the synthesizer's own claim, so it does
# not count as a citation.
_QUOTE = re.compile(r"^\s*>")

# A bare issue/PR/discussion reference. The lookbehind keeps `#N` out of
# URLs (`…/pull/123`) and identifiers (`abc#1`); `\b` ends it at the
# number so `#12a` does not match `#12`.
_REF = re.compile(r"(?<![\w/])#(\d+)\b")


def cited_numbers(body: str) -> list[int]:
    """Return the `#N` a doc body cites, deduplicated, in appearance order.

    Syntactic only: strips fenced and inline code, drops block-quote
    lines, then matches bare `#N`. The numbers are not yet checked
    against the corpus — a hex colour like `#282828` survives here and
    is rejected by the caller's corpus filter.
    """
    prose = _CODE.sub(" ", body)
    lines = [line for line in prose.splitlines() if not _QUOTE.match(line)]
    seen: dict[int, None] = {}
    for match in _REF.finditer("\n".join(lines)):
        seen.setdefault(int(match.group(1)), None)
    return list(seen)


def build_index(store: Store, design_dir: Path) -> IndexSummary:
    """Build the topic index from the docs in `design_dir` and the mirror.

    Reads every `<topic>.md` beside `INDEX.md` as a synthesized entry —
    its `description:` hook and its body's corpus-resolved, heat-ordered
    citations — then folds in the routing mirror's topics that no doc
    covers yet as pending entries. Entries come back alphabetical by
    name; the synthesized and pending ones interleave, because the
    reader is looking up a subject, not auditing synthesis progress.

    The `Store` dependency lives here and nowhere else in the module:
    `cited_numbers` and `render_index` are pure.
    """
    entries: dict[str, IndexEntry] = {}
    for path in sorted(design_dir.glob("*.md")):
        if path.name == "INDEX.md":
            continue
        description, body = _read_doc(path)
        entries[path.stem] = IndexEntry(
            name=path.stem,
            synthesized=True,
            description=description,
            numbers=_resolve_citations(store, cited_numbers(body)),
        )
    _add_pending_topics(store, entries)
    return IndexSummary(entries=[entries[name] for name in sorted(entries)])


def _resolve_citations(store: Store, numbers: list[int]) -> list[int]:
    """Keep the numbers the corpus resolves, scored ones heat-ordered first.

    Issues and PRs come back ordered by heat — `heat_scores_for` both
    filters to the present ones and ranks them — and discussions, which
    carry no heat score, follow in ascending number order. A number the
    corpus does not carry (a hex colour, another project's tracker)
    resolves to neither and drops out.
    """
    scored = store.heat_scores_for(HEAT_WEIGHTS, numbers)
    discussions = store.discussion_numbers_in(numbers)
    return [int(score.number) for score in scored] + [int(n) for n in discussions]


def _add_pending_topics(store: Store, entries: dict[str, IndexEntry]) -> None:
    """Add a pending entry for each routed topic no doc already covers.

    A pending topic has no file, so its numbers come from the items
    triage routed to it — mapped to numbers through the corpus, then
    heat-ordered like a synthesized doc's citations. A topic that a
    synthesized doc already covers is left as it is: the doc, not the
    routing mirror, is the authority once one exists.
    """
    number_of = {item.id: item.number for item in store.all_issues_and_prs()}
    routed: dict[str, list[int]] = {}
    for route in store.routes():
        number = number_of.get(route.item_id)
        if number is not None:
            routed.setdefault(route.verdict, []).append(int(number))
    for topic in store.topics():
        if topic.name in entries:
            continue
        scored = store.heat_scores_for(HEAT_WEIGHTS, routed.get(topic.name, []))
        entries[topic.name] = IndexEntry(
            name=topic.name,
            synthesized=False,
            description=None,
            numbers=[int(score.number) for score in scored],
        )


class _Frontmatter(msgspec.Struct):
    """The one frontmatter field `index` reads: the doc's hook line.

    Other fields may sit alongside it; a default `msgspec.Struct`
    ignores them, so only `description` is required to be present and a
    string. Its absence is what raises `MalformedFrontmatterError`.
    """

    description: str


def _read_doc(path: Path) -> tuple[str, str]:
    """Return a doc's `description` and body, or raise on bad frontmatter.

    Splits the leading `---` fence structurally, then parses the fenced
    block as YAML through `msgspec`. Any failure — no opening fence, an
    unclosed one, unparseable YAML, or a missing/non-string
    `description` — becomes a `MalformedFrontmatterError` naming the
    file, never a silently blank index line.
    """
    fence, body = _split_fence(path.read_text(encoding="utf-8"), path)
    try:
        matter = msgspec.yaml.decode(fence, type=_Frontmatter)
    except (msgspec.DecodeError, msgspec.ValidationError) as exc:
        raise MalformedFrontmatterError(path) from exc
    return matter.description, body


def _split_fence(text: str, path: Path) -> tuple[str, str]:
    """Split a leading `---`-fenced frontmatter block from the body.

    Structural, not a regex over prose: the first line must be the opening fence
    and some later line must close it. Returns the block between the fences and
    everything after, both without their fence lines.
    """
    lines = text.split("\n")
    if not lines or lines[0].strip() != "---":
        raise MalformedFrontmatterError(path)
    for index in range(1, len(lines)):
        if lines[index].strip() == "---":
            return "\n".join(lines[1:index]), "\n".join(lines[index + 1 :])
    raise MalformedFrontmatterError(path)


def render_index(summary: IndexSummary) -> str:
    """Render `summary` to the INDEX.md markdown text.

    Pure: entries in the order the summary holds them (alphabetical by
    name, as `build_index` produces), each capped at five numbers. An
    empty summary renders the header alone.
    """
    if not summary.entries:
        return _HEADER
    lines = "\n".join(_render_entry(entry) for entry in summary.entries)
    return f"{_HEADER}\n{lines}\n"


def _render_entry(entry: IndexEntry) -> str:
    """Render one entry: a linked line if synthesized, a flagged one if not."""
    suffix = _number_suffix(entry.numbers)
    if entry.synthesized:
        return f"- [{entry.name}]({entry.name}.md) — {entry.description}{suffix}"
    return f"- {entry.name} — *not yet synthesized*{suffix}"


def _number_suffix(numbers: list[int]) -> str:
    """Return the ` (#a, #b, …)` suffix, capped at five numbers, or ``.

    Empty when the topic rests on no resolvable citation. `…` is appended — as a
    sixth comma-separated token — whenever the full set exceeds the cap, so the
    reader sees the line is a hook, not the whole bibliography.
    """
    if not numbers:
        return ""
    shown = [f"#{number}" for number in numbers[:_MAX_NUMBERS]]
    if len(numbers) > _MAX_NUMBERS:
        shown.append("…")
    return f" ({', '.join(shown)})"
